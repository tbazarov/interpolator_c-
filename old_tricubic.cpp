bool TricubicInterpolator::insideBounds(const Vector3D& pos) const {
    return (pos[0] >= m_xMin && pos[0] <= m_xMax &&
            pos[1] >= m_yMin && pos[1] <= m_yMax &&
            pos[2] >= m_zMin && pos[2] <= m_zMax);
}

size_t TricubicInterpolator::cellIndex(int i, int j, int k) const {
    //return static_cast<size_t>(i + (m_nx - 1) * (j + (m_ny - 1) * k));
    return static_cast<size_t>(i * (m_nz-1) * (m_ny-1) + (m_nz-1) * j + k);
}

size_t TricubicInterpolator::nodeIndex(int i, int j, int k) const {
    i = std::clamp(i, 0, m_nx - 1);
    j = std::clamp(j, 0, m_ny - 1);
    k = std::clamp(k, 0, m_nz - 1);
    //return static_cast<size_t>(i + m_nx * (j + m_ny * k));
    return static_cast<size_t>(i * m_nz * m_ny + m_nz * j + k);
}

double TricubicInterpolator::evaluatePolynomial(
    const std::array<double, 64>& coeffs, double tx, double ty, double tz
) const {
    double tx2 = tx * tx, tx3 = tx2 * tx;
    double ty2 = ty * ty, ty3 = ty2 * ty;
    double tz2 = tz * tz, tz3 = tz2 * tz;
    const double t[4] = {1.0, tx, tx2, tx3};
    const double u[4] = {1.0, ty, ty2, ty3};
    const double v[4] = {1.0, tz, tz2, tz3};

    double result = 0.0;
    int idx = 0;
    for (int i = 0; i < 4; ++i)
        for (int j = 0; j < 4; ++j)
            for (int k = 0; k < 4; ++k) {
                result += coeffs[idx] * t[i] * u[j] * v[k];
                ++idx;
            }
    return result;
}

// === Численные производные ===
void TricubicInterpolator::computeAllDerivatives(
    const std::vector<double>& f,
    int i, int j, int k,
    double& f_val,
    double& fx, double& fy, double& fz,
    double& fxy, double& fyz, double& fzx,
    double& fxyz
) const {
    auto get = [&](int di, int dj, int dk) -> double {
        return f[nodeIndex(i + di, j + dj, k + dk)];
    };

    f_val = get(0, 0, 0);

    // Первые производные
    fx = (i > 0 && i < m_nx - 1) ? (get(+1,0,0) - get(-1,0,0)) / (2*m_dx) :
          (i == 0) ? (get(+1,0,0) - get(0,0,0)) / m_dx :
                     (get(0,0,0) - get(-1,0,0)) / m_dx;

    fy = (j > 0 && j < m_ny - 1) ? (get(0,+1,0) - get(0,-1,0)) / (2*m_dy) :
          (j == 0) ? (get(0,+1,0) - get(0,0,0)) / m_dy :
                     (get(0,0,0) - get(0,-1,0)) / m_dy;

    fz = (k > 0 && k < m_nz - 1) ? (get(0,0,+1) - get(0,0,-1)) / (2*m_dz) :
          (k == 0) ? (get(0,0,+1) - get(0,0,0)) / m_dz :
                     (get(0,0,0) - get(0,0,-1)) / m_dz;

    // Смешанные вторые
    fxy = (i > 0 && i < m_nx - 1 && j > 0 && j < m_ny - 1) ?
          (get(+1,+1,0) - get(+1,-1,0) - get(-1,+1,0) + get(-1,-1,0)) / (4*m_dx*m_dy) : 0.0;

    fyz = (j > 0 && j < m_ny - 1 && k > 0 && k < m_nz - 1) ?
          (get(0,+1,+1) - get(0,+1,-1) - get(0,-1,+1) + get(0,-1,-1)) / (4*m_dy*m_dz) : 0.0;

    fzx = (k > 0 && k < m_nz - 1 && i > 0 && i < m_nx - 1) ?
          (get(+1,0,+1) - get(+1,0,-1) - get(-1,0,+1) + get(-1,0,-1)) / (4*m_dz*m_dx) : 0.0;

    // Третья смешанная
    fxyz = (i > 0 && i < m_nx - 1 && j > 0 && j < m_ny - 1 && k > 0 && k < m_nz - 1) ?
           (get(+1,+1,+1) - get(+1,+1,-1) - get(+1,-1,+1) + get(+1,-1,-1)
            -get(-1,+1,+1) + get(-1,+1,-1) + get(-1,-1,+1) - get(-1,-1,-1)) / (8*m_dx*m_dy*m_dz) : 0.0;
}

