TricubicInterpolator::TricubicInterpolator(
    double xMin, double xMax, int nx,
    double yMin, double yMax, int ny,
    double zMin, double zMax, int nz,
    const std::vector<Vector3D>& fieldValues
)
    : m_xMin(xMin), m_xMax(xMax)
    , m_yMin(yMin), m_yMax(yMax)
    , m_zMin(zMin), m_zMax(zMax)
    , m_nx(std::max(2, nx))
    , m_ny(std::max(2, ny))
    , m_nz(std::max(2, nz))
{
    if (fieldValues.size() != static_cast<size_t>(m_nx * m_ny * m_nz)) {
        throw std::invalid_argument("Field values size mismatch");
    }

    m_dx = (m_nx > 1) ? (m_xMax - m_xMin) / (m_nx - 1) : 1.0;
    m_dy = (m_ny > 1) ? (m_yMax - m_yMin) / (m_ny - 1) : 1.0;
    m_dz = (m_nz > 1) ? (m_zMax - m_zMin) / (m_nz - 1) : 1.0;

    // Подготовка компонент
    std::vector<double> Bx(m_nx * m_ny * m_nz);
    std::vector<double> By(m_nx * m_ny * m_nz);
    std::vector<double> Bz(m_nx * m_ny * m_nz);
    for (size_t i = 0; i < fieldValues.size(); ++i) {
        Bx[i] = fieldValues[i][0];
        By[i] = fieldValues[i][1];
        Bz[i] = fieldValues[i][2];
    }

    m_coeffs.resize((m_nx - 1) * (m_ny - 1) * (m_nz - 1));

    // Обработка каждой ячейки
    for (int k = 0; k < m_nz - 1; ++k)
        for (int j = 0; j < m_ny - 1; ++j)
            for (int i = 0; i < m_nx - 1; ++i) {
                std::array<double, 8> f_x, fx_x, fy_x, fz_x, fxy_x, fyz_x, fzx_x, fxyz_x;
                std::array<double, 8> f_y, fx_y, fy_y, fz_y, fxy_y, fyz_y, fzx_y, fxyz_y;
                std::array<double, 8> f_z, fx_z, fy_z, fz_z, fxy_z, fyz_z, fzx_z, fxyz_z;

                int v = 0;
                for (int dk = 0; dk < 2; ++dk)
                    for (int dj = 0; dj < 2; ++dj)
                        for (int di = 0; di < 2; ++di) {
                            computeAllDerivatives(Bx, i+di, j+dj, k+dk,
                                f_x[v], fx_x[v], fy_x[v], fz_x[v],
                                fxy_x[v], fyz_x[v], fzx_x[v], fxyz_x[v]);

                            computeAllDerivatives(By, i+di, j+dj, k+dk,
                                f_y[v], fx_y[v], fy_y[v], fz_y[v],
                                fxy_y[v], fyz_y[v], fzx_y[v], fxyz_y[v]);

                            computeAllDerivatives(Bz, i+di, j+dj, k+dk,
                                f_z[v], fx_z[v], fy_z[v], fz_z[v],
                                fxy_z[v], fyz_z[v], fzx_z[v], fxyz_z[v]);
                            ++v;
                        }

                auto& cell = m_coeffs[cellIndex(i, j, k)];
                computeCoefficientsFromDerivatives(f_x, fx_x, fy_x, fz_x, fxy_x, fyz_x, fzx_x, fxyz_x, cell[0]);
                computeCoefficientsFromDerivatives(f_y, fx_y, fy_y, fz_y, fxy_y, fyz_y, fzx_y, fxyz_y, cell[1]);
                computeCoefficientsFromDerivatives(f_z, fx_z, fy_z, fz_z, fxy_z, fyz_z, fzx_z, fxyz_z, cell[2]);
            }
}

Vector3D TricubicInterpolator::interpolate(const Vector3D& position) const {
    if (!insideBounds(position)) {
        return {0.0, 0.0, 0.0};
    }

    double xf = (m_dx > 0) ? (position[0] - m_xMin) / m_dx : 0.0;
    double yf = (m_dy > 0) ? (position[1] - m_yMin) / m_dy : 0.0;
    double zf = (m_dz > 0) ? (position[2] - m_zMin) / m_dz : 0.0;

    int i = static_cast<int>(std::floor(xf));
    int j = static_cast<int>(std::floor(yf));
    int k = static_cast<int>(std::floor(zf));

    if (i >= m_nx - 2) i = m_nx - 3;
    if (j >= m_ny - 2) j = m_ny - 3;
    if (k >= m_nz - 2) k = m_nz - 3;

    double tx = xf - i;
    double ty = yf - j;
    double tz = zf - k;

    const auto& coeffs = m_coeffs[cellIndex(i, j, k)];

    return {
        evaluatePolynomial(coeffs[0], tx, ty, tz),
        evaluatePolynomial(coeffs[1], tx, ty, tz),
        evaluatePolynomial(coeffs[2], tx, ty, tz)
    };
}
